CREATE TABLE branch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

-- 차량과 지점의 관계 및 운영 상태·금액의 기본 규칙을 DB에서도 검사한다.
CREATE TABLE vehicle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES branch(id),
    name VARCHAR(100) NOT NULL,
    seats INTEGER NOT NULL CHECK (seats > 0),
    daily_price BIGINT NOT NULL CHECK (daily_price >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('AVAILABLE', 'MAINTENANCE'))
);

-- 지점·상태 필터와 ID 오름차순 정렬을 지원한다.
CREATE INDEX idx_vehicle_branch_status_id ON vehicle (branch_id, status, id);